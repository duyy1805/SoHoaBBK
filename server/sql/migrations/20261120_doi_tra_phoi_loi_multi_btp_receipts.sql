      AND name=N'UX_DTPL_PHIEU_NHAP_BTP_ActiveProcess')
    CREATE UNIQUE INDEX UX_DTPL_PHIEU_NHAP_BTP_ActiveProcess
        ON dbo.DOI_TRA_PHOI_LOI_PHIEU_NHAP_BTP(PhieuId,SourceQuyTrinhSanXuatId)
