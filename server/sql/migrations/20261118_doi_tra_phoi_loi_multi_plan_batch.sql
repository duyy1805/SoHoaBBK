SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.DOI_TRA_PHOI_LOI_NHOM',N'U') IS NULL
BEGIN
    CREATE TABLE dbo.DOI_TRA_PHOI_LOI_NHOM(
        Id INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_DTPL_NHOM PRIMARY KEY,
        SoPhieu NVARCHAR(50) NOT NULL,
        NgayLap DATE NOT NULL,
        NguoiLapId INT NOT NULL,
        LegacyPhieuId INT NULL,
        CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_DTPL_NHOM_CreatedAt DEFAULT SYSDATETIME(),
        UpdatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_DTPL_NHOM_UpdatedAt DEFAULT SYSDATETIME(),
        RowVersion ROWVERSION NOT NULL,
        CONSTRAINT UQ_DTPL_NHOM_SoPhieu UNIQUE(SoPhieu),
        CONSTRAINT FK_DTPL_NHOM_NguoiLap FOREIGN KEY(NguoiLapId) REFERENCES dbo.USERS(Id)
    );
END;

IF EXISTS(SELECT 1 FROM sys.key_constraints WHERE parent_object_id=OBJECT_ID(N'dbo.DOI_TRA_PHOI_LOI_NHOM') AND name=N'UQ_DTPL_NHOM_LegacyPhieu')
    ALTER TABLE dbo.DOI_TRA_PHOI_LOI_NHOM DROP CONSTRAINT UQ_DTPL_NHOM_LegacyPhieu;
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.DOI_TRA_PHOI_LOI_NHOM') AND name=N'UX_DTPL_NHOM_LegacyPhieu')
    CREATE UNIQUE INDEX UX_DTPL_NHOM_LegacyPhieu
        ON dbo.DOI_TRA_PHOI_LOI_NHOM(LegacyPhieuId) WHERE LegacyPhieuId IS NOT NULL;

IF COL_LENGTH(N'dbo.DOI_TRA_PHOI_LOI',N'NhomPhieuId') IS NULL
    ALTER TABLE dbo.DOI_TRA_PHOI_LOI ADD NhomPhieuId INT NULL;
IF COL_LENGTH(N'dbo.DOI_TRA_PHOI_LOI',N'ThuTuKeHoach') IS NULL
    ALTER TABLE dbo.DOI_TRA_PHOI_LOI ADD ThuTuKeHoach INT NULL;

GO

INSERT dbo.DOI_TRA_PHOI_LOI_NHOM(SoPhieu,NgayLap,NguoiLapId,LegacyPhieuId,CreatedAt,UpdatedAt)
SELECT phieu.SoPhieu,phieu.NgayLap,phieu.NguoiLapId,phieu.Id,phieu.CreatedAt,phieu.UpdatedAt
FROM dbo.DOI_TRA_PHOI_LOI phieu
WHERE phieu.NhomPhieuId IS NULL
  AND NOT EXISTS(SELECT 1 FROM dbo.DOI_TRA_PHOI_LOI_NHOM nhom WHERE nhom.LegacyPhieuId=phieu.Id);

UPDATE phieu
SET NhomPhieuId=nhom.Id,ThuTuKeHoach=1
FROM dbo.DOI_TRA_PHOI_LOI phieu
JOIN dbo.DOI_TRA_PHOI_LOI_NHOM nhom ON nhom.LegacyPhieuId=phieu.Id
WHERE phieu.NhomPhieuId IS NULL;

IF EXISTS(SELECT 1 FROM dbo.DOI_TRA_PHOI_LOI WHERE NhomPhieuId IS NULL)
    THROW 52500,N'Không thể chuyển toàn bộ phiếu đổi trả cũ sang nhóm kế hoạch.',1;

ALTER TABLE dbo.DOI_TRA_PHOI_LOI ALTER COLUMN NhomPhieuId INT NOT NULL;
ALTER TABLE dbo.DOI_TRA_PHOI_LOI ALTER COLUMN ThuTuKeHoach INT NOT NULL;

IF NOT EXISTS(SELECT 1 FROM sys.foreign_keys WHERE parent_object_id=OBJECT_ID(N'dbo.DOI_TRA_PHOI_LOI') AND name=N'FK_DTPL_NhomPhieu')
    ALTER TABLE dbo.DOI_TRA_PHOI_LOI WITH CHECK ADD CONSTRAINT FK_DTPL_NhomPhieu
        FOREIGN KEY(NhomPhieuId) REFERENCES dbo.DOI_TRA_PHOI_LOI_NHOM(Id);

IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.DOI_TRA_PHOI_LOI') AND name=N'UX_DTPL_Nhom_ThuTu')
    CREATE UNIQUE INDEX UX_DTPL_Nhom_ThuTu ON dbo.DOI_TRA_PHOI_LOI(NhomPhieuId,ThuTuKeHoach);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.DOI_TRA_PHOI_LOI') AND name=N'IX_DTPL_Nhom')
    CREATE INDEX IX_DTPL_Nhom ON dbo.DOI_TRA_PHOI_LOI(NhomPhieuId,Id);

COMMIT;
GO
